CREATE OR REPLACE FUNCTION public.app_has_access()
 RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$
  select exists (select 1 from profiles p where p.id = auth.uid() and p.active
                 and (p.role <> 'site' or p.discipline is not null));
$function$;

CREATE OR REPLACE FUNCTION public.can_see_project(p text)
 RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$ select app_role() in ('admin','planner','pm')
   or exists (select 1 from project_members m where m.project_id = p and m.user_id = auth.uid()) $function$;

CREATE OR REPLACE FUNCTION public.admin_activity(p_limit integer DEFAULT 300, p_demo boolean DEFAULT false)
 RETURNS TABLE(at timestamp with time zone, user_id uuid, who text, role text, kind text, tbl text, row_id text, old_row jsonb, new_row jsonb)
 LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'public'
AS $function$
begin
  if app_role() is distinct from 'admin' then raise exception 'Admins only'; end if;
  return query
  select * from (
    select l.at, l.user_id, p.full_name, p.role::text, 'login'::text, null::text, null::text, null::jsonb, jsonb_build_object('ua', l.ua)
    from login_log l left join profiles p on p.id = l.user_id
    union all
    select a.at, a.actor, p.full_name, p.role::text, lower(a.action), a.table_name, a.row_id,
           a.old_row - 'photos' - 'log' - 'html' - 'image',
           a.new_row - 'photos' - 'log' - 'html' - 'image'
    from audit_log a left join profiles p on p.id = a.actor
    where p_demo or not (coalesce(a.new_row, a.old_row)->>'source' = 'demo' or coalesce((coalesce(a.new_row, a.old_row)->>'is_demo')::boolean, false)
                         or a.row_id like 'R_seed%')
  ) x order by 1 desc limit greatest(1, least(p_limit, 2000));
end $function$;

CREATE OR REPLACE FUNCTION public.admin_set_password(p_user uuid, p_password text)
 RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions', 'auth'
AS $function$
begin
  if app_role() is distinct from 'admin' then
    raise exception 'Only an administrator can reset passwords';
  end if;
  if p_password is null or length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters';
  end if;
  update auth.users
     set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')),
         updated_at = now()
   where id = p_user;
  if not found then raise exception 'User not found'; end if;
  insert into public.audit_log(table_name, row_id, action, old_row, new_row)
  values ('profiles', p_user::text, 'PASSWORD', null,
          jsonb_build_object('id', p_user, 'full_name', (select full_name from public.profiles where id = p_user)));
end $function$;

CREATE OR REPLACE FUNCTION public.audit_row()
 RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$ begin
  insert into audit_log(table_name,row_id,action,old_row,new_row)
  values (tg_table_name, coalesce(new.id, old.id)::text, tg_op,
          case when tg_op <> 'INSERT' then to_jsonb(old) end,
          case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return coalesce(new, old);
end $function$;

CREATE OR REPLACE FUNCTION public.audit_row_any()
 RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare r jsonb := to_jsonb(coalesce(new, old));
begin
  insert into audit_log(table_name, row_id, action, old_row, new_row)
  values (tg_table_name, coalesce(r->>'id', r->>'key', (r->>'project_id') || ':' || (r->>'user_id')), tg_op,
          case when tg_op <> 'INSERT' then to_jsonb(old) - 'html' end,
          case when tg_op <> 'DELETE' then to_jsonb(new) - 'html' end);
  return coalesce(new, old);
end $function$;

