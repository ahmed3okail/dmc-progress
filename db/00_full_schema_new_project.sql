-- ========== Views ==========
create or replace view public.v_activity_progress as
 SELECT id, project_id, code, name, name_ar, wbs, zone, building, planned_start, planned_finish,
    budget_qty, unit, weight, discipline, source, is_demo, updated_at,
        CASE
            WHEN (CURRENT_DATE < planned_start) THEN (0)::numeric
            WHEN (CURRENT_DATE >= planned_finish) THEN (100)::numeric
            ELSE round(((100.0 * ((CURRENT_DATE - planned_start))::numeric) / (GREATEST(1, (planned_finish - planned_start)))::numeric), 1)
        END AS planned_pct,
    COALESCE(( SELECT u.pct
           FROM progress_updates u
          WHERE ((u.activity_id = a.id) AND (u.status = 'approved'::update_status))
          ORDER BY u.reviewed_at DESC
         LIMIT 1), 0) AS approved_pct
   FROM activities a;

create or replace view public.v_project_progress as
 SELECT p.id, p.code, p.name, p.contract_value, p.is_demo,
    round((sum((v.weight * v.planned_pct)) / NULLIF(sum(v.weight), (0)::numeric)), 1) AS planned_pct,
    round((sum((v.weight * (v.approved_pct)::numeric)) / NULLIF(sum(v.weight), (0)::numeric)), 1) AS actual_pct
   FROM (projects p
     JOIN v_activity_progress v ON ((v.project_id = p.id)))
  GROUP BY p.id;

